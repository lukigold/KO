# --------------------------------------------------------------------------- helpers

def R(sheet, ref, value, key, a, b, **kw):
    return sheet.add(ref, "Device:R", value, {"1": a, "2": b}, footprint=FP_R0402, **lcsc(key), **kw)


def C(sheet, ref, value, key, a, b="GND", **kw):
    pkg = key.split("_")[2]
    return sheet.add(ref, "Device:C", value, {"1": a, "2": b}, footprint=FP_C[pkg], **lcsc(key), **kw)


def TP(sheet, ref, net):
    return sheet.add(ref, "Connector:TestPoint", net, {"1": net}, footprint="TestPoint:TestPoint_Pad_D1.0mm",
                     in_bom=False)


