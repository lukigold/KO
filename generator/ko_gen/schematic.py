"""Switch board schematic, generated from a layout (layout.Board) with kisch.

Fixed blocks (every board): core contacts, port B, column shift registers, LED driver(s) with I2C isolation,
descriptor EEPROM. Generated blocks: one socket + diode per key (matrix), one RGB LED per key and per underglow
position (driver channels from layout.assign_leds). Circuit and parts: docs/design/switch-board-v1.md section 2.
"""
from __future__ import annotations

import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "hardware" / "tools"))
from kisch.schematic import Design, ic_symbol  # noqa: E402

PARTS = {r["key"]: r for r in csv.DictReader(open(ROOT / "hardware" / "switch" / "bom" / "parts.csv"))}
FIXED = {   # verified by hand where the API search does not find the MPN (date of the check)
    "U_74HC595": ("C431479", "74HC595D(BJ)"),
    "U_24C02": ("C283436", "M24C02-WDW6TP"),
    "U_USBLC6": ("C5261088", "USBLC6-2SC6"),
    "J_USBC_HX": ("C41427495", "HX TYPE-C 16P L10.0"),
    "LED_E6CC1205": ("C2802677", "E6CC1205RGBC3UDA"),
    "J_CHOC_SOCKET": ("", "Kailh CPG135001S30"),
}
FP_R, FP_C = "Resistor_SMD:R_0402_1005Metric", "Capacitor_SMD:C_0402_1005Metric"
FP_C0805 = "Capacitor_SMD:C_0805_2012Metric"
KO = "ko-switch:"

# core interface, switch-board contract (contact -> signal)
CONTACTS = {1: "VBUS_B", 2: "VBUS_B", 3: "VBUS_B", 4: "GND", 5: "USB_B_DN", 6: "USB_B_DP", 7: "GND", 8: "VLOGIC",
            9: "I2C_SCL", 10: "I2C_SDA", 11: "GND", 12: "GND", 13: "GND", 14: "LED_5V", 15: "LED_5V", 16: "LED_5V",
            17: "GND", 18: "LED_SDB", 19: "ROW7", 20: "ROW6", 21: "CC1_B", 22: "ROW5", 23: "CC2_B", 24: "ROW4",
            25: "RSV_MISO", 26: "COL_LAT", 27: "COL_DAT", 28: "COL_CLK", 29: "RSV_INT", 30: "ROW0", 31: "ROW1",
            32: "ROW2", 33: "ROW3"}

IS31_PINS = {7: "INTB", 8: "ADDR", 9: "SDA", 10: "SCL", 11: "SDB", 12: "GND", 13: "ISET", 14: "AVCC", 15: "PVCC",
             25: "PVCC", 36: "GND", 55: "GND", 61: "EP"}
for i in range(9):
    IS31_PINS[16 + i] = f"SW{i + 1}"
for i, pin in enumerate(list(range(26, 36)) + list(range(37, 55)) + list(range(56, 61)) + list(range(1, 7))):
    IS31_PINS[pin] = f"CS{i + 1}"          # CS1-10: 26-35, CS11-28: 37-54, CS29-33: 56-60, CS34-39: 1-6


def lcsc(key):
    if key in FIXED:
        return {"lcsc": FIXED[key][0], "mpn": FIXED[key][1]}
    r = PARTS[key]
    return {"lcsc": r["lcsc"], "mpn": r["mfr"]}


def cs_of(slot: int, colour: str) -> int:
    """CS line (1-based) of a slot's colour, as in the datasheet's RGB circuit (fig. 2): R on CS3s+3, G on 3s+2,
    B on 3s+1."""
    return 3 * slot + {"B": 1, "G": 2, "R": 3}[colour]


def build(b) -> Design:
    d = Design(project=b.slug, title=f"KO switch board: {b.name}", rev="v1", company="KO - Keyboard Organization",
               comments=["SPDX-License-Identifier: CERN-OHL-S-2.0",
                         "Implements docs/contracts/switch-board.md; see docs/design/switch-board-v1.md",
                         "Generated by generator/ko_gen from the KO layout file - edit the layout, not KiCad"])
    d.add_symbol("kosw", ic_symbol(
        "IS31FL3741A", datasheet="https://www.lumissil.com/assets/pdf/core/IS31FL3741A_DS.pdf",
        description="39x9 dot matrix LED driver, I2C, QFN-60 7x7",
        left=[("14", "AVCC", "power_in"), ("15", "PVCC", "power_in"), ("25", "PVCC", "power_in", True),
              ("9", "SDA", "bidirectional"), ("10", "SCL", "input"), ("11", "SDB", "input"),
              ("8", "ADDR", "input"), ("7", "INTB", "open_collector"), ("13", "ISET", "passive")],
        right=[(str(p), n, "passive") for p, n in sorted(IS31_PINS.items()) if n.startswith("SW")],
        top=[(str(p), n, "passive") for p, n in sorted(IS31_PINS.items(), key=lambda t: (len(t[1]), t[1]))
             if n.startswith("CS")],
        bottom=[("12", "GND", "power_in"), ("36", "GND", "power_in", True), ("55", "GND", "power_in", True),
                ("61", "GND", "power_in", True)],
        footprint=KO + "Lumissil_QFN-60_7x7mm_P0.4mm_EP5.4mm"))
    d.add_symbol("kosw", ic_symbol(
        "LED_RGB_CA", ref="D", description="RGB LED, common anode (E6CC1205RGBC3UDA: 2 = anode, 1 R, 3 G, 4 B)",
        left=[("2", "A", "passive")], right=[("1", "R", "passive"), ("3", "G", "passive"), ("4", "B", "passive")]))

    def R(s, ref, val, key, a, c):
        s.add(ref, "Device:R", val, {"1": a, "2": c}, footprint=FP_R, **lcsc(key))

    def C(s, ref, val, key, a, c="GND", fp=FP_C):
        s.add(ref, "Device:C", val, {"1": a, "2": c}, footprint=fp, **lcsc(key))

    # ---------------------------------------------------------------- core contacts, port B
    s = d.sheet("Core and port B", "core_port_b.kicad_sch", paper="A3", note=(
        "33 castellated contacts to the core strip (switch-board contract, SWB-016); unused rows and the reserved lines\n"
        "stay unconnected. USB-C port B at the back-left corner (SWB-015): VBUS_B, D+/D- and CC straight to the core,\n"
        "ESD arrays next to the receptacle; Rd and CC sensing are on the core."))
    used_rows = {f"ROW{r}" for r in range(b.rows)}
    pins = {}
    for c, net in CONTACTS.items():
        nc = (net.startswith("ROW") and net not in used_rows) or net.startswith("RSV")
        pins[str(c)] = "NC" if nc else net
    s.add("J1", "Connector_Generic:Conn_01x33", "Core contacts", pins, footprint=KO + "Castellated_1x33_P2.00mm_Edge_Right_1-17_18-33",
          in_bom=False)
    s.add("J2", "Connector:USB_C_Receptacle_USB2.0_16P", "USB-C B", {
        "VBUS": "VBUS_B", "GND": "GND", "SHIELD": "GND", "CC1": "CC1_B", "CC2": "CC2_B", "D+": "USB_B_DP",
        "D-": "USB_B_DN", "SBU1": "NC", "SBU2": "NC"}, footprint=KO + "USB_C_Receptacle_HX_TYPE-C-16P_L10.0",
        **lcsc("J_USBC_HX"))
    s.add("U1", "Power_Protection:USBLC6-2SC6", "USBLC6-2SC6", {
        "1": "USB_B_DN", "6": "USB_B_DN", "3": "USB_B_DP", "4": "USB_B_DP", "5": "VBUS_B", "2": "GND"},
        footprint="Package_TO_SOT_SMD:SOT-23-6", **lcsc("U_USBLC6"))
    s.add("U2", "Power_Protection:USBLC6-2SC6", "USBLC6-2SC6", {
        "1": "CC1_B", "6": "CC1_B", "3": "CC2_B", "4": "CC2_B", "5": "VBUS_B", "2": "GND"},
        footprint="Package_TO_SOT_SMD:SOT-23-6", **lcsc("U_USBLC6"))
    for i, net in enumerate(("VBUS_B", "VLOGIC", "LED_5V", "GND") + (("LED_REF",) if b.drivers else ())):
        s.add(f"#FLG{i + 1}", "power:PWR_FLAG", "PWR_FLAG", {"1": net}, in_bom=False)

    # ---------------------------------------------------------------- control
    s = d.sheet("Control", "control.kicad_sch", paper="A3", note=(
        "Columns: 74HC595 chain from VLOGIC (COL_DAT -> SER, QH' -> next SER), 8 columns per register, COL2ROW.\n"
        "LED driver(s): IS31FL3741A from LED_5V (off by default); PCA9306 opens the I2C bus to them only while LED_5V\n"
        "is on (EN tied to VREF2), so an unpowered driver never loads the shared bus. Descriptor EEPROM at 0x50."))
    R(s, "R1", "33", "R_33_0402", "COL_CLK", "COL_SCK")
    for i in range(b.regs):
        q = {f"Q{chr(65 + j)}": (f"COL{8 * i + j}" if 8 * i + j < b.cols else "NC") for j in range(8)}
        q.update({"SER": "COL_DAT" if i == 0 else f"COL_SER{i}", "QH'": f"COL_SER{i + 1}" if i < b.regs - 1 else "NC",
                  "SRCLK": "COL_SCK", "RCLK": "COL_LAT", "~{SRCLR}": "VLOGIC", "~{OE}": "GND",
                  "VCC": "VLOGIC", "GND": "GND"})
        s.add(f"U{10 + i}", "74xx:74HC595", "74HC595", q, footprint="Package_SO:SOIC-16_3.9x9.9mm_P1.27mm",
              **lcsc("U_74HC595"))
        C(s, f"C{10 + i}", "100n", "C_100n_0402", "VLOGIC")
    s.add("U3", "Memory_EEPROM:M24C02-WDW", "M24C02", {"E0": "GND", "E1": "GND", "E2": "GND", "VSS": "GND",
          "VCC": "VLOGIC", "SDA": "I2C_SDA", "SCL": "I2C_SCL", "~{WC}": "GND"},
          footprint="Package_SO:TSSOP-8_4.4x3mm_P0.65mm", **lcsc("U_24C02"))
    C(s, "C3", "100n", "C_100n_0402", "VLOGIC")
    if b.drivers and (b.glow or any(k.led for k in b.keys)):
        s.add("U4", "Interface:PCA9306", "PCA9306", {"GND": "GND", "VREF1": "VLOGIC", "SCL1": "I2C_SCL",
              "SDA1": "I2C_SDA", "VREF2": "LED_REF", "EN": "LED_REF", "SCL2": "LED_SCL", "SDA2": "LED_SDA"},
              footprint="Package_SO:VSSOP-8_2.3x2mm_P0.5mm", **lcsc("U_PCA9306"))
        R(s, "R2", "200k", "R_200k_0402", "LED_5V", "LED_REF")
        C(s, "C4", "100n", "C_100n_0402", "LED_REF")
        R(s, "R3", "10k", "R_10k_0402", "LED_SCL", "LED_5V")
        R(s, "R4", "10k", "R_10k_0402", "LED_SDA", "LED_5V")
        R(s, "R5", "100k", "R_100k_0402", "LED_SDB", "GND")
        C(s, "C5", "10u", "C_10u_0805", "LED_5V", fp=FP_C0805)
        for n in range(b.drivers):
            u = f"U{20 + n}"
            p = {"AVCC": "LED_5V", "PVCC": "LED_5V", "SDA": "LED_SDA", "SCL": "LED_SCL", "SDB": "LED_SDB",
                 "ADDR": "GND" if n == 0 else "LED_SCL", "INTB": "NC", "ISET": f"LED_ISET{n}", "GND": "GND"}
            for i in range(9):
                p[f"SW{i + 1}"] = f"D{n}_SW{i + 1}"
            for i in range(39):
                p[f"CS{i + 1}"] = f"D{n}_CS{i + 1}"
            s.add(u, "kosw:IS31FL3741A", "IS31FL3741A", p, footprint=KO + "Lumissil_QFN-60_7x7mm_P0.4mm_EP5.4mm",
                  **lcsc("U_IS31FL3741A"))
            R(s, f"R{20 + n}", "10k", "R_10k_0402", f"LED_ISET{n}", "GND")
            for j, pin in enumerate(("14", "15", "25")):
                C(s, f"C{20 + 10 * n + 2 * j}", "1u", "C_1u_0402", "LED_5V")
                C(s, f"C{21 + 10 * n + 2 * j}", "100n", "C_100n_0402", "LED_5V")

    # ---------------------------------------------------------------- keys (one sheet per row)
    keys = sorted(b.keys, key=lambda k: (k.row, k.x))
    for i, k in enumerate(keys):
        k.ref = i + 1
    for r in range(b.rows):
        s = d.sheet(f"Keys row {r}", f"keys_row{r}.kicad_sch", paper="A3",
                    note=f"Row {r}: socket (Choc v1/v2 hot-swap) and diode per key, COL2ROW (SWB-006).")
        for k in (k for k in keys if k.row == r):
            node = f"K_{k.id}"
            s.add(f"SW{k.ref}", "Switch:SW_Push", k.id, {"1": f"COL{k.col}", "2": node},
                  footprint=KO + "Key_Choc_V1V2_Hotswap_CPG1350", **lcsc("J_CHOC_SOCKET"))
            s.add(f"D{100 + k.ref}", "Device:D", "1N4148W", {"A": node, "K": f"ROW{r}"},
                  footprint="Diode_SMD:D_SOD-123", **lcsc("D_1N4148W"))

    # ---------------------------------------------------------------- LEDs (one sheet per driver SW line group)
    leds = [(f"D{300 + k.ref}", k.led, f"key {k.id}") for k in keys if k.led]
    leds += [(f"D{500 + i + 1}", g.led, "underglow") for i, g in enumerate(b.glow) if g.led]
    for n in range(b.drivers):
        for half, sws in enumerate(((0, 1, 2, 3), (4, 5, 6, 7, 8))):
            mine = [t for t in leds if t[1][0] == n and t[1][1] in sws]
            if not mine:
                continue
            s = d.sheet(f"LEDs driver {n} part {half + 1}", f"leds_d{n}_{half + 1}.kicad_sch", paper="A3",
                        note=f"Driver {n}: anodes on SW lines {', '.join(str(x + 1) for x in sws)}, cathodes on CS "
                             "(R = CS3s+3, G = 3s+2, B = 3s+1 for slot s). Key LEDs reverse mount, underglow facing down.")
            for ref, (dn, sw, slot), what in sorted(mine, key=lambda t: t[1]):
                s.add(ref, "kosw:LED_RGB_CA", "E6CC1205RGBC3UDA", {
                    "A": f"D{dn}_SW{sw + 1}", "R": f"D{dn}_CS{cs_of(slot, 'R')}", "G": f"D{dn}_CS{cs_of(slot, 'G')}",
                    "B": f"D{dn}_CS{cs_of(slot, 'B')}"},
                    footprint=KO + ("LED_E6CC1205RGBC3UDA_ReverseMount" if what != "underglow"
                                    else "LED_E6CC1205RGBC3UDA_Underglow"), **lcsc("LED_E6CC1205"))
    return d


def unused_driver_pins(d: Design) -> None:
    """CS/SW lines of a driver that no LED uses would be single-pin nets: mark them NC."""
    nets = d.nets()
    for s in d.sheets:
        for p in s.parts:
            if p.lib_id == "kosw:IS31FL3741A":
                for k, v in list(p.pins.items()):
                    if v.startswith("D") and "_" in v and len(nets.get(v, [])) < 2:
                        p.pins[k] = "NC"


def write(b, outdir: pathlib.Path) -> Design:
    d = build(b)
    unused_driver_pins(d)
    problems = d.check()
    if problems:
        raise SystemExit("\n".join(problems))
    d.write(outdir)
    return d
